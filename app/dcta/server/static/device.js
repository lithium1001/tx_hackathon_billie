/* Billie — the customer's device: a signing key and the gateway client.
   The private key is generated by WebCrypto as NON-EXTRACTABLE and kept in
   IndexedDB, so neither this page's scripts nor any server can read it — they
   can only ask the browser to sign with it. Signed transactions go from here
   straight to the gateway; the agent process never sees them. */
'use strict';

const Device = (() => {
  const DB = 'dcta-device';
  const STORE = 'keys';
  const memory = {};   // fallback when IndexedDB is unavailable (private window)

  function idb(mode, fn) {
    return new Promise((resolve, reject) => {
      const open = indexedDB.open(DB, 1);
      open.onupgradeneeded = () => open.result.createObjectStore(STORE);
      open.onerror = () => reject(open.error);
      open.onsuccess = () => {
        const tx = open.result.transaction(STORE, mode);
        const req = fn(tx.objectStore(STORE));
        tx.oncomplete = () => resolve(req.result);
        tx.onerror = () => reject(tx.error);
      };
    });
  }

  async function keyPair(customerId) {
    let kp = memory[customerId];
    if (!kp) {
      try { kp = await idb('readonly', (s) => s.get(customerId)); } catch (e) { /* no IndexedDB */ }
    }
    if (!kp) {
      kp = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' },
                                           false /* private key not extractable */, ['sign', 'verify']);
      try { await idb('readwrite', (s) => s.put(kp, customerId)); } catch (e) { /* memory only */ }
    }
    memory[customerId] = kp;
    return kp;
  }

  function b64url(bytes) {
    let s = '';
    bytes.forEach((b) => { s += String.fromCharCode(b); });
    return btoa(s).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
  }

  async function post(gatewayUrl, path, body) {
    try {
      const resp = await fetch(gatewayUrl + path, {
        method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
      });
      return { ok: resp.ok, status: resp.status, body: await resp.json() };
    } catch (e) {
      return { ok: false, status: 0, body: { error: 'GATEWAY_UNREACHABLE' } };
    }
  }

  // The gateway keeps device keys in memory, so the public key is registered
  // again on every sign-in; the key pair itself stays the same.
  async function register(gatewayUrl, customerId) {
    const kp = await keyPair(customerId);
    const { kty, crv, x, y } = await crypto.subtle.exportKey('jwk', kp.publicKey);
    const r = await post(gatewayUrl, '/v1/devices', { customer_id: customerId, jwk: { kty, crv, x, y } });
    return r.ok ? r.body.key_id : null;
  }

  // ECDSA P-256 / SHA-256 over the exact UTF-8 bytes the gateway issued. WebCrypto
  // returns r‖s (p1363), which is the format the gateway expects.
  async function sign(customerId, signingInput) {
    const kp = await keyPair(customerId);
    const sig = await crypto.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, kp.privateKey,
                                         new TextEncoder().encode(signingInput));
    return { alg: 'ES256', format: 'p1363', value: b64url(new Uint8Array(sig)) };
  }

  const challenge = (gw, groupCanonical, keyId, traceId) =>
    post(gw, '/v1/challenges', { group: groupCanonical, key_id: keyId, trace_id: traceId || '' });

  const submit = (gw, challengeId, signingInput, signature, otp) =>
    post(gw, '/v1/transactions', { challenge_id: challengeId, signing_input: signingInput,
                                   signature, otp: otp || null });

  // Gateway codes in the customer's words.
  const ERRORS = {
    SIGNATURE_MISSING: 'The payment was not signed on this device.',
    SIGNATURE_INVALID: "This device's signature didn't check out.",
    PAYLOAD_TAMPERED: 'The payment details changed after you approved them.',
    NONCE_REPLAYED: 'This approval has already been used.',
    CHALLENGE_EXPIRED: 'This approval timed out.',
    CHALLENGE_UNKNOWN: "The bank didn't recognise this approval.",
    KEY_UNKNOWN: "This device isn't registered for your account.",
    NOT_OWNED: "One of the accounts or payees isn't yours.",
    RISK_DENIED: "The bank's safety checks declined this payment.",
    STEP_UP_REQUIRED: 'The verification code is missing or wrong.',
    INSUFFICIENT_FUNDS: "There isn't enough money in the account.",
    GATEWAY_UNREACHABLE: "Couldn't reach the bank. Nothing was sent.",
  };
  const explain = (code) => ERRORS[code] || 'The bank declined this payment.';

  return { register, sign, challenge, submit, explain };
})();
